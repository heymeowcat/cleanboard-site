#!/usr/bin/env node
/**
 * generate-capture-list.mjs
 *
 * Builds the list of strings whose transliteration we want to learn, so the
 * capture is systematic rather than ad hoc.
 *
 * The list covers every part of the scheme:
 *
 *   1. every single letter, lower and upper case
 *   2. every consonant, on its own and followed by a vowel
 *   3. every vowel, alone and in every doubled form, in a final and a
 *      medial position
 *   4. every aspirate (consonant + h)
 *   5. every geminate (a doubled consonant)
 *   6. every cluster (r and y after a consonant, plus the "sr"/"pr" pairs)
 *   7. the nasal clusters (nd, nk, nh, ng, nnd, nndh)
 *   8. a vocabulary of real words
 *
 * Usage: node scripts/generate-capture-list.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");

const CONSONANTS = [
    "k", "g", "c", "j", "t", "d", "n", "p", "b", "m", "r", "l", "w", "y",
    "s", "h", "f", "v", "z",
];
const VOWELS = ["a", "e", "i", "o", "u"];
const VOWEL_PAIRS = ["aa", "ee", "ii", "oo", "uu", "ai", "au", "ay", "ei", "ou", "ia", "ua"];

const list = [];
const add = (value) => {
    if (value && !list.includes(value)) list.push(value);
};

// 1. Single letters
for (const c of "abcdefghijklmnopqrstuvwxyz") add(c);
for (const c of "ABCDEFGHIJKLMNOPQRSTUVWXYZ") add(c);

// 2. Every consonant followed by a vowel (final position)
for (const c of CONSONANTS) for (const v of VOWELS) add(c + v);

// 3. Every vowel, final and medial
for (const v of VOWELS) {
    add(v);
    add("k" + v + "a");
}
for (const v of VOWEL_PAIRS) {
    add(v);
    add("k" + v + "a");
    add("k" + v);
}

// 4. Aspirates — every consonant + h
for (const c of CONSONANTS) {
    add(c + "ha");
    add(c + "hi");
}

// 5. Geminates — every doubled consonant
for (const c of CONSONANTS) {
    add(c + c + "a");
    add(c + c + "i");
}

// 6. Clusters — r and y after a consonant
for (const c of CONSONANTS) {
    add(c + "ra");
    add(c + "ru");
    add(c + "ya");
    add(c + "yu");
}
for (const p of ["sr", "pr", "tr", "br", "gr", "dr", "kr", "fr", "shr", "thr", "phr"]) {
    add(p + "a");
    add(p + "i");
}

// 7. Nasal clusters
const TAILS = [
    "da", "ka", "ga", "ha", "tha", "dha", "cha", "sha", "pha", "bha", "ma",
    "ta", "pa", "ba", "la", "ya", "ra", "wa", "na", "sa",
];
for (const tail of TAILS) {
    add("n" + tail);
    add("nn" + tail);
}
for (const tail of ["da", "ha", "tha"]) add("nnd" + tail);

// 8. Vocabulary
const WORDS = [
    "ayubowan", "kohomada", "hodai", "mokada", "mokakda", "kawda", "koheda",
    "subha", "divasak", "karunakara", "apu", "mata", "thaththa",
    "amma", "akka", "ayya", "aachchi", "malli", "nangi", "seeya",
    "mama", "oya", "api", "eyala", "yamu", "nam", "honda",
    "sinhala", "lanka", "colombo", "kandy", "galle", "negombo", "jaffna",
    "kurunegala", "anuradhapura", "matale", "ratnapura", "badulla",
    "hambantota", "puttalam", "trincomalee", "batticaloa", "vavuniya",
    "monaragala",
    "goda", "gaha", "pala", "malu", "kalu", "hala", "pamba", "paha", "pani",
    "pila", "kanda", "panda", "kuta", "gula", "mata", "matha", "patha", "ratha",
    "maha", "bala", "sala", "dola", "pola", "kola", "niri", "nimal", "kiri",
    "diri", "mili", "pili", "seeya", "sina", "tuli", "vaha", "vatika",
    "nam", "yana", "ayana",
    "kanna", "danna", "yanna", "balanna", "bonna", "karanna", "dena",
    "genna", "enna", "hena", "panna", "tanna", "wenna", "kawada", "ganna",
    "hanna", "kana", "nanna", "sanna", "wanna", "yana",
    "budu", "saranai", "adi", "keles", "watta",
    "govi", "mahanama", "ratna", "mudal", "weeraya", "jana", "pokuna",
    "gaman", "ithin", "thawa", "thama", "kohomadaa",
    "sinhali", "prarthanawa", "gihilla", "dannawa", "karunakarala",
    "kamala", "sunil", "ruwan", "chandana", "tharindu", "lahiru",
];
for (const w of WORDS) add(w);

const outPath = resolve(projectRoot, "src/data/capture-list.json");
writeFileSync(
    outPath,
    JSON.stringify(
        {
            _comment:
                "The strings to capture, generated by scripts/generate-capture-list.mjs",
            entries: list,
        },
        null,
        2,
    ) + "\n",
    "utf8",
);

console.log(`✔ ${list.length} strings → ${outPath.replace(projectRoot, ".")}`);
