#!/usr/bin/env node
/**
 * build-dictionary.mjs
 *
 * Generates the Kotlin files the Android app needs from the website's shared
 * data, so the app and the website can never disagree:
 *
 *   • `SinglishDictionary.kt`     — the word dictionary (Singlish → Sinhala)
 *   • `ReferenceCorpusTest.kt`      — the captured ground truth, as a
 *                                   JUnit fixture the app asserts against
 *
 * The app's transliteration *rules* live in Kotlin (they are a port of this
 * website's engine); the *data* is generated from here.
 *
 * Usage:
 *   node scripts/build-dictionary.mjs [path/to/CleanBoard]
 *
 * Default target:
 *   ~/AndroidStudioProjects/CleanBoard
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");

const appRoot = resolve(
    process.argv[2] ?? join(homedir(), "AndroidStudioProjects/CleanBoard"),
);
const kotlinDir = resolve(
    appRoot,
    "app/src/main/java/com/heymeowcat/cleanboard/keyboard",
);
const testDir = resolve(
    appRoot,
    "app/src/test/java/com/heymeowcat/cleanboard/keyboard",
);

const readJson = (name) =>
    JSON.parse(readFileSync(resolve(projectRoot, "src/data", name), "utf8"));

const dictionary = readJson("reference-dictionary.json");
const corpus = readJson("reference-corpus.json");

/** Kotlin string literals must escape backslashes, quotes and $ */
const kotlinString = (value) =>
    `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

// --- SinglishDictionary.kt -------------------------------------------------

const dictionaryEntries = Object.entries(dictionary)
    .map(([word, sinhala]) => `        ${kotlinString(word)} to ${kotlinString(sinhala)},`)
    .join("\n");

// The website ranks transliteration candidates with only the top 20,000
// words. The app's model has ~92,000, so it must clamp to the same cutoff —
// otherwise a word outside the website's list could outrank the rule's
// answer in the app and the two would disagree.
const frequencyLines = readFileSync(
    resolve(projectRoot, "public/data/si-words.txt"),
    "utf8",
)
    .trim()
    .split("\n");
const lastFrequencyLine = frequencyLines[frequencyLines.length - 1];
const minRankingFrequency = Number(
    lastFrequencyLine.slice(lastFrequencyLine.lastIndexOf(" ") + 1),
);

const dictionaryFile = `package com.heymeowcat.cleanboard.keyboard

/**
 * The Singlish → Sinhala word dictionary.
 *
 * GENERATED by the CleanBoard website's \`npm run build:dictionary\`.
 * Do not edit by hand — edit \`src/data/reference-dictionary.json\` in the
 * website repository and re-run the generator.
 *
 * These are the words whose spelling cannot be derived from the letter
 * rules alone, because Sinhala writes them differently. The website uses
 * the same list, so the app and the website always type a word the same way.
 */
object SinglishDictionary {

    /**
     * The lowest count in the website's 20,000-word ranking list.
     *
     * The app's n-gram model has more words than the website ships, but the
     * transliterator ignores anything below this cutoff so that both rank
     * candidates with exactly the same data.
     */
    const val MIN_RANKING_FREQUENCY = ${minRankingFrequency}

    /** Every known word, in Singlish → Sinhala. */
    val entries: Map<String, String> = mapOf(
${dictionaryEntries}
    )

    /** True when the word has a canonical spelling. */
    fun isKnown(word: String): Boolean = entries.containsKey(word.lowercase())

    /** The canonical spelling, or null when the word is not in the list. */
    fun get(word: String): String? = entries[word.lowercase()]
}
`;

mkdirSync(kotlinDir, { recursive: true });
writeFileSync(resolve(kotlinDir, "SinglishDictionary.kt"), dictionaryFile, "utf8");
console.log(
    `✔ SinglishDictionary.kt — ${Object.keys(dictionary).length} words → ${kotlinDir.replace(appRoot, ".")}`,
);

// --- ReferenceCorpusTest.kt ---------------------------------------------------

/**
 * Only the words that are in the dictionary are asserted exactly. The corpus
 * also holds isolated fragments (single letters, consonant + vowel, …) which
 * are ground truth for the rules but are not words, and which need the
 * frequency model to resolve — the app resolves those with its n-gram model
 * at runtime.
 */
const corpusEntries = Object.entries(corpus.entries)
    .filter(([word]) => Object.prototype.hasOwnProperty.call(dictionary, word))
    .map(([word, candidates]) => {
        const expected = candidates[0];
        return `        ${kotlinString(word)} to ${kotlinString(expected)},`;
    })
    .join("\n");

const corpusFile = `package com.heymeowcat.cleanboard.keyboard

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * The ground truth captured from a reference implementation of the
 * standard Singlish scheme.
 *
 * GENERATED by the CleanBoard website's \`npm run build:dictionary\`.
 * Do not edit by hand — edit \`src/data/reference-corpus.json\` in the website
 * repository and re-run the generator.
 *
 * Every word below must be produced by the app's transliterator, so the
 * keyboard types Sinhala exactly the way the website does.
 */
class ReferenceCorpusTest {

    private val expected = mapOf(
${corpusEntries}
    )

    @Test
    fun \`every captured word matches the reference exactly\`() {
        val failures = mutableListOf<String>()

        for ((word, reference) in expected) {
            val ours = SinglishTransliterator.finalize(word)
            if (ours != reference) {
                failures.add("$word: expected $reference, got $ours")
            }
        }

        assertEquals(
            "These words no longer match the reference:\\n" + failures.joinToString("\\n"),
            emptyList<String>(),
            failures,
        )
    }

    @Test
    fun \`the corpus is not empty\`() {
        assertEquals(true, expected.isNotEmpty())
    }
}
`;

mkdirSync(testDir, { recursive: true });
writeFileSync(resolve(testDir, "ReferenceCorpusTest.kt"), corpusFile, "utf8");
console.log(
    `✔ ReferenceCorpusTest.kt — ${corpusEntries.split("\n").length} assertions → ${testDir.replace(appRoot, ".")}`,
);

// --- RuleParityTest.kt --------------------------------------------------------

// The app's rules are a Kotlin port of the website's engine. This test is
// generated from the website engine itself, so any drift between the two
// implementations fails the app's build.
const engineBundle = await build({
    entryPoints: [resolve(projectRoot, "src/lib/transliterator.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    write: false,
    logLevel: "silent",
});
const engine = await import(
    "data:text/javascript;base64," +
        Buffer.from(engineBundle.outputFiles[0].text).toString("base64")
);

const heldout = readJson("reference-heldout.json");
const parityKeys = [
    ...new Set([
        ...Object.keys(corpus.entries),
        ...Object.keys(heldout.entries),
        ...Object.keys(dictionary),
    ]),
].sort();

const parityEntries = parityKeys
    .map(
        (word) =>
            `        ${kotlinString(word)} to ${kotlinString(engine.transliterateLiteral(word))},`,
    )
    .join("\n");

const parityFile = `package com.heymeowcat.cleanboard.keyboard

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * The letter rules, checked one word at a time against the website engine.
 *
 * GENERATED by the CleanBoard website's \`npm run build:dictionary\`.
 * Do not edit by hand — edit \`src/lib/transliterator.ts\` in the website
 * repository and re-run the generator.
 *
 * This is a *rule* test: it bypasses the dictionary and the word-frequency
 * ranking on both sides, so it isolates the port from the data.
 */
class RuleParityTest {

    private val expected = mapOf(
${parityEntries}
    )

    @Test
    fun \`the letter rules match the website\`() {
        val failures = mutableListOf<String>()

        for ((word, reference) in expected) {
            val ours = SinglishTransliterator.transliterateLiteral(word)
            if (ours != reference) {
                failures.add("$word: expected $reference, got $ours")
            }
        }

        assertEquals(
            "The app's rules no longer match the website's:\\n" + failures.joinToString("\\n"),
            emptyList<String>(),
            failures,
        )
    }

    @Test
    fun \`the rule corpus is not empty\`() {
        assertEquals(true, expected.isNotEmpty())
    }
}
`;

writeFileSync(resolve(testDir, "RuleParityTest.kt"), parityFile, "utf8");
console.log(
    `✔ RuleParityTest.kt — ${parityKeys.length} rule cases → ${testDir.replace(appRoot, ".")}`,
);
